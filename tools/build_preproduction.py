def source_link(s):
    return f"[原稿 L{s['source_start']}–L{s['source_end']}](../../未抵达的心意.md)"


def write_scene_docs():
    chapters = list(dict.fromkeys(s['chapter'] for s in SCENES))
    index = ['# 《未抵达的心意》分景索引', '',
        '版本：制作拆解 v0.1｜2026-10-18。原稿保持不变。', '',
        '场是地点、时间、视角或情绪目标的制作单元；节拍是一次信息揭示、动作或情绪改变。它不是逐句台词终稿，也不代表每拍都要另画一张图。', '',
        '来源行号按当前原稿计算；编辑原稿后需要重新核对。本文记录的镜头、演出、资产编号均是新增制作建议。', '',
        '| 编号 | 分景 | 时空 | 角色 | 原稿行号 | 背景 |',
        '|---|---|---|---|---|---|']
    for n, chapter in enumerate(chapters, 1):
        filename = f'{n:02d}_{chapter}_分景.md'
        body = [f'# {chapter}：分景明细', '',
            '说明：剧情事实来自原稿；镜头、表情调度、音响和素材划分均为制作建议。背景编号见《美术资产表》，连续性编号见《连续性与定稿事项》。', '']
        for s in [x for x in SCENES if x['chapter'] == chapter]:
            index.append(f"| {s['id']} | [{s['title']}]({filename}#{s['id'].lower()}) | {s['time']}／{s['place']} | {s['cast']} | {s['source_start']}–{s['source_end']} | {s['background']} |")
            body.extend([f"<a id=\"{s['id'].lower()}\"></a>", f"## {s['id']}｜{s['title']}", '',
                f"- 原稿：{source_link(s)}。", f"- 时间／空间：{s['time']}；{s['place']}。",
                f"- 出场：{s['cast']}。", f"- 剧情作用：{s['purpose']}", f"- 情绪过程：{s['emotion']}。",
                f"- 背景：{s['background']}。", f"- 画面资产：{s['art']}", '', '**演出节拍**', ''])
            for beat in s['beats']:
                number, content = beat.split(' ', 1)
                body.append(f"{int(number)}. **{s['id']}-B{number}** {content}")
            body.extend(['', f"**收束与承接：** {s['exit']}", '', f"**连续性：** {s['continuity']}", ''])
        (OUT / filename).write_text('\n'.join(body) + '\n', encoding='utf-8')
    index.extend(['', f"共 {len(SCENES)} 个制作分景、{sum(len(s['beats']) for s in SCENES)} 个演出节拍。", '',
        '本索引覆盖序章、六章共同线和完整DeepSeek线；Claude、GPT、Normal End正文原稿尚未提供，不新增虚构结局。'])
    (OUT / '分景索引.md').write_text('\n'.join(index) + '\n', encoding='utf-8')


